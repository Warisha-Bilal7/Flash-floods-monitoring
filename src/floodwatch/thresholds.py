"""Train-only threshold fitting and the D-01 validation invariant guard.

Thresholds are fitted on ``split == "train"`` rows only. Validation is used
exclusively to *check* the fitted cutoffs: a drift beyond the tolerance is
recorded and escalated, never silently refitted.

``configs/thresholds.yaml`` is machine-generated by
``scripts/05_fit_thresholds.py``. It carries a ``provenance_fingerprint`` over
the fitted numbers; ``validate_thresholds`` recomputes it so a hand-edit turns
the contract tests red.
"""

from __future__ import annotations

import hashlib
import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import pandas as pd
import yaml

from . import schema
from .models import eval as metrics
from .tiers import TIERS

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_PATH = ROOT / "configs" / "thresholds.yaml"

TIER_NAMES: tuple[str, ...] = ("low", "moderate", "high", "severe")
ALL_TIER_KEYS: tuple[str, ...] = ("none",) + TIER_NAMES

POD_TOLERANCE = 0.10
FAR_TOLERANCE = 0.10
DEFAULT_TARGET_FAR = 0.40
DEFAULT_MIN_POD = 0.50


# ---------------------------------------------------------------------------
# Fit
# ---------------------------------------------------------------------------
def _candidates() -> list[float]:
    return [round(i / 100.0, 4) for i in range(1, 100)]


def choose_operating_point(
    y_true: pd.Series,
    y_score: pd.Series,
    *,
    target_far: float = DEFAULT_TARGET_FAR,
    min_pod: float = DEFAULT_MIN_POD,
) -> tuple[float, dict[str, float]]:
    """Pick the cutoff that maximises CSI subject to the POD/FAR objectives.

    Falls back to the best CSI point when no candidate meets both objectives,
    then to 0.5 when the sample has no positives.
    """
    truth = pd.Series(y_true).astype(bool)
    score = pd.Series(y_score).astype(float)
    if truth.empty or not truth.any():
        return 0.5, {"pod": 0.0, "far": 0.0, "csi": 0.0}

    best_feasible: tuple[float, dict[str, float]] | None = None
    best_any: tuple[float, dict[str, float]] | None = None
    for cutoff in _candidates():
        block = {
            "pod": metrics.pod(truth, score, cutoff),
            "far": metrics.far(truth, score, cutoff),
            "csi": metrics.csi(truth, score, cutoff),
        }
        if best_any is None or block["csi"] > best_any[1]["csi"]:
            best_any = (cutoff, block)
        feasible = block["far"] <= target_far and block["pod"] >= min_pod
        if feasible and (best_feasible is None or block["csi"] > best_feasible[1]["csi"]):
            best_feasible = (cutoff, block)
    chosen = best_feasible or best_any
    assert chosen is not None
    return chosen


def _quantile(values: pd.Series, q: float, default: float) -> float:
    clean = pd.to_numeric(values, errors="coerce").dropna()
    if clean.empty:
        return default
    return float(clean.quantile(q))


def fit_tier_cutoffs(
    predictions: pd.DataFrame,
    *,
    target_far: float = DEFAULT_TARGET_FAR,
    min_pod: float = DEFAULT_MIN_POD,
) -> dict[str, Any]:
    """Fit monotonic tier cutoffs from one mechanism's train predictions.

    ``predictions`` needs ``prob`` and ``label``. ``high`` is the alert
    operating point; ``moderate`` and ``low`` sit below it, ``severe`` above.
    """
    frame = predictions.dropna(subset=["prob", "label"])
    if "split" in frame.columns:
        # Never fit on validation or test rows, even if a caller passes them.
        frame = frame[frame["split"].astype(str) == "train"]
    if frame.empty:
        cutoffs = {"none": 0.0, "low": 0.02, "moderate": 0.10, "high": 0.30, "severe": 0.60}
        return {
            "tiers": cutoffs,
            "operating_point": {"pod": 0.0, "far": 0.0, "csi": 0.0},
            "rows": 0,
        }

    high, operating = choose_operating_point(
        frame["label"], frame["prob"], target_far=target_far, min_pod=min_pod
    )
    positives = frame.loc[frame["label"].astype(int) == 1, "prob"]
    severe = max(high + 0.10, _quantile(positives, 0.90, min(0.99, high + 0.15)))
    moderate = max(0.01, high * 0.60)
    low = max(0.005, moderate * 0.50)

    # Enforce strict monotonicity inside [0, 1].
    severe = min(0.999, max(severe, high + 0.001))
    high = min(high, severe - 0.001)
    moderate = min(moderate, high - 0.001)
    low = min(low, moderate - 0.001)

    cutoffs = {
        "none": 0.0,
        "low": round(max(0.0, low), 4),
        "moderate": round(max(0.0, moderate), 4),
        "high": round(max(0.0, high), 4),
        "severe": round(max(0.0, severe), 4),
    }
    return {
        "tiers": cutoffs,
        "operating_point": {
            "pod": round(float(operating["pod"]), 4),
            "far": round(float(operating["far"]), 4),
            "csi": round(float(operating["csi"]), 4),
        },
        "rows": int(len(frame)),
    }


def metrics_at_cutoff(predictions: pd.DataFrame, cutoff: float) -> dict[str, float]:
    frame = predictions.dropna(subset=["prob", "label"])
    if frame.empty:
        return {"pod": 0.0, "far": 0.0, "csi": 0.0, "rows": 0.0}
    truth = frame["label"].astype(int)
    score = frame["prob"].astype(float)
    return {
        "pod": round(metrics.pod(truth, score, cutoff), 4),
        "far": round(metrics.far(truth, score, cutoff), 4),
        "csi": round(metrics.csi(truth, score, cutoff), 4),
        "rows": float(len(frame)),
    }


def validation_guard(
    train_metrics: dict[str, float],
    validation_metrics: dict[str, float],
    *,
    pod_tolerance: float = POD_TOLERANCE,
    far_tolerance: float = FAR_TOLERANCE,
) -> dict[str, Any]:
    """D-01 check. Returns deltas and a pass flag; never refits."""
    pod_delta = round(
        float(validation_metrics.get("pod", 0.0)) - float(train_metrics.get("pod", 0.0)), 4
    )
    far_delta = round(
        float(validation_metrics.get("far", 0.0)) - float(train_metrics.get("far", 0.0)), 4
    )
    passed = abs(pod_delta) <= pod_tolerance + 1e-9 and abs(far_delta) <= far_tolerance + 1e-9
    return {
        "pod_train": round(float(train_metrics.get("pod", 0.0)), 4),
        "pod_validation": round(float(validation_metrics.get("pod", 0.0)), 4),
        "far_train": round(float(train_metrics.get("far", 0.0)), 4),
        "far_validation": round(float(validation_metrics.get("far", 0.0)), 4),
        "pod_delta": pod_delta,
        "far_delta": far_delta,
        "pod_tolerance": pod_tolerance,
        "far_tolerance": far_tolerance,
        "pass": bool(passed),
        "action": "ok" if passed else "escalate_joint_decision",
    }


# ---------------------------------------------------------------------------
# Machine-generated YAML
# ---------------------------------------------------------------------------
def _canonical_modules(modules: dict[str, Any]) -> str:
    payload = {
        name: {
            "tiers": {key: round(float(block["tiers"][key]), 6) for key in ALL_TIER_KEYS},
        }
        for name, block in sorted(modules.items())
    }
    return json.dumps(payload, sort_keys=True, separators=(",", ":"))


def fingerprint(config: dict[str, Any]) -> str:
    """Hash the fitted numbers only, so comments/formatting do not matter."""
    return hashlib.sha256(_canonical_modules(config.get("modules", {})).encode("utf-8")).hexdigest()


def build_config(
    modules: dict[str, dict[str, Any]],
    *,
    data_snapshot_hash: str,
    generated_at: str | None = None,
    guard: dict[str, Any] | None = None,
    target_far: float = DEFAULT_TARGET_FAR,
    min_pod: float = DEFAULT_MIN_POD,
) -> dict[str, Any]:
    config: dict[str, Any] = {
        "schema_version": 1,
        "generated_by": "scripts/05_fit_thresholds.py",
        "fitted_on": "train",
        "data_snapshot_hash": data_snapshot_hash,
        "generated_at": generated_at or datetime.now(UTC).isoformat(),
        "objective": {"target_far": target_far, "min_pod": min_pod},
        "modules": modules,
        "guard": guard
        or {
            "pod_tolerance": POD_TOLERANCE,
            "far_tolerance": FAR_TOLERANCE,
            "pass": all(block.get("drift", {}).get("pass", True) for block in modules.values()),
        },
    }
    config["provenance_fingerprint"] = fingerprint(config)
    return config


def save_thresholds(config: dict[str, Any], path: str | Path | None = None) -> Path:
    p = Path(path or DEFAULT_PATH)
    p.parent.mkdir(parents=True, exist_ok=True)
    body = dict(config)
    body.setdefault("provenance_fingerprint", fingerprint(config))
    header = (
        "# MACHINE-GENERATED by scripts/05_fit_thresholds.py — do not hand-edit.\n"
        "# Re-run the script after any model or data change; contract tests\n"
        "# recompute provenance_fingerprint and fail on a manual edit.\n"
    )
    p.write_text(
        header + yaml.safe_dump(body, sort_keys=False, allow_unicode=True), encoding="utf-8"
    )
    return p


def load_thresholds(path: str | Path | None = None) -> dict[str, Any]:
    p = Path(path or DEFAULT_PATH)
    data = yaml.safe_load(p.read_text(encoding="utf-8")) or {}
    if not isinstance(data, dict):
        raise ValueError(f"{p}: expected a mapping")
    if data.get("fitted_on") != "train":
        raise ValueError(f"{p}: fitted_on must be 'train', got {data.get('fitted_on')!r}")
    return data


def validate_thresholds(config: dict[str, Any]) -> None:
    """Raise when a config is hand-edited, incomplete or non-monotonic."""
    problems: list[str] = []
    if config.get("fitted_on") != "train":
        problems.append("fitted_on must be 'train'")
    if "provenance_fingerprint" not in config:
        problems.append("provenance_fingerprint missing")
    elif config["provenance_fingerprint"] != fingerprint(config):
        problems.append(
            "provenance_fingerprint mismatch: thresholds were edited by hand; "
            "re-run scripts/05_fit_thresholds.py"
        )
    modules = config.get("modules") or {}
    if not modules:
        problems.append("modules block is empty")
    for name, block in modules.items():
        tiers = (block or {}).get("tiers") or {}
        missing = [key for key in ALL_TIER_KEYS if key not in tiers]
        if missing:
            problems.append(f"{name}: missing tier cutoffs {missing}")
            continue
        values = [float(tiers[key]) for key in ALL_TIER_KEYS]
        if any(not (0.0 <= value <= 1.0) for value in values):
            problems.append(f"{name}: cutoffs outside [0, 1]")
        if any(b <= a for a, b in zip(values, values[1:], strict=False)):
            problems.append(f"{name}: cutoffs are not strictly increasing: {values}")
    if problems:
        raise ValueError("invalid thresholds config:\n  - " + "\n  - ".join(problems))


def module_tiers(config: dict[str, Any], module: str) -> dict[str, float]:
    block = (config.get("modules") or {}).get(module)
    if block is None:
        raise KeyError(f"thresholds config has no block for module {module!r}")
    return {key: float(block["tiers"][key]) for key in ALL_TIER_KEYS}


def tier_for(prob: float, cutoffs: dict[str, float]) -> str:
    """Delegate to the shared schema helper (one tier rule, one place)."""
    return schema.tier_for(prob, cutoffs)


def expected_tiers() -> tuple[str, ...]:
    return TIERS


def drift_breaches(config: dict[str, Any]) -> list[str]:
    """Every module whose validation drift exceeded the agreed tolerance."""
    out: list[str] = []
    for name, block in (config.get("modules") or {}).items():
        drift = (block or {}).get("drift") or {}
        if drift and not drift.get("pass", True):
            out.append(name)
    return out
